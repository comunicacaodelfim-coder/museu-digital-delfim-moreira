const archiveViewer = document.createElement('dialog');
archiveViewer.className = 'archive-viewer';
archiveViewer.setAttribute('aria-labelledby', 'archive-viewer-title');
document.body.append(archiveViewer);
let archiveReturnFocus = null;

function openArchiveImage(id, trigger) {
  const item = museumContent.images[id];
  if (!item) return;
  archiveReturnFocus = trigger;
  archiveViewer.classList.remove('is-zoomed');
  archiveViewer.innerHTML = `<div class="archive-viewer-top"><span>${item.plaque ? 'PLAQUINHA DO ACERVO' : 'IMAGEM DO ACERVO'}</span><div><button type="button" class="archive-zoom">Aumentar imagem</button><button type="button" class="archive-close" autofocus aria-label="Fechar imagem">Fechar ×</button></div></div><div class="archive-image-scroll"><img class="archive-viewer-image" src="${new URL(item.src, museumScriptBase).href}" alt="${museumEscape(item.alt)}" style="--archive-zoom-width:${Math.max(item.width * 2, 900)}px"></div><div class="archive-viewer-caption"><h2 id="archive-viewer-title">${museumEscape(item.title)}</h2>${(item.transcript || []).map(text => `<p>${museumEscape(text)}</p>`).join('')}</div>`;
  archiveViewer.querySelector('.archive-close').onclick = () => archiveViewer.close();
  const zoom = archiveViewer.querySelector('.archive-zoom');
  zoom.onclick = () => {
    const enlarged = archiveViewer.classList.toggle('is-zoomed');
    zoom.textContent = enlarged ? 'Ajustar imagem' : 'Aumentar imagem';
    zoom.setAttribute('aria-pressed', String(enlarged));
  };
  zoom.setAttribute('aria-pressed', 'false');
  archiveViewer.showModal();
  document.body.classList.add('viewer-open');
}

document.addEventListener('click', event => {
  const trigger = event.target.closest('[data-acervo]');
  if (trigger) openArchiveImage(trigger.dataset.acervo, trigger);
});
archiveViewer.addEventListener('close', () => {
  document.body.classList.remove('viewer-open');
  if (archiveReturnFocus?.isConnected) archiveReturnFocus.focus({preventScroll: true});
});
archiveViewer.addEventListener('click', event => {
  if (event.target === archiveViewer) archiveViewer.close();
});
